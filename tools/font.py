FIRST, LAST = 0x20, 0x5F          # ' ' .. '_'


def rows_1bpp(ch: str) -> list[int]:
    """8 bytes, one per row, bit 7 leftmost. Blank for anything undefined."""
    glyph = GLYPHS.get(ch.upper())
    if glyph is None:
        return [0] * 8
    out = []
    for row in glyph:
        bits = 0
        for col, c in enumerate(row):
            if c == '#':
                bits |= 0x80 >> col
        out.append(bits)
    out.append(0)                 # 8th row is descender space
    return out


def ascii_range() -> range:
    return range(FIRST, LAST + 1)
